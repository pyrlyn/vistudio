    internal static void Run(string root, Action<bool, string> check)
    {
        var folder = Path.Combine(root, "cargo-unit");
        Directory.CreateDirectory(folder);
        var manifest = Path.Combine(folder, "Cargo.toml");
        File.WriteAllText(manifest, Manifest);
        File.WriteAllText(Path.Combine(folder, "Cargo.lock"), Lock);
        var cargo = new CargoPackageManager();

        check(cargo.Ecosystem == PackageEcosystem.Cargo && cargo.DisplayName == "Cargo" && cargo.ManifestNames.SequenceEqual(new[] { "Cargo.toml" }), "cargo identity");
        Reading(cargo, manifest, check);
        Locks(cargo, root, check);
        Report(cargo, root, check);
        Requirements(cargo, check);
        Commands(cargo, manifest, folder, check);
    }

    private static void Reading(CargoPackageManager cargo, string manifest, Action<bool, string> check)
    {
        var entries = cargo.ReadManifest(manifest);
        var names = string.Join(",", entries.Select(e => e.Name));
        check(names == "serde,anyhow,local,fork,shared,inherited,alias,quoted-key,tokio,regex,criterion,cc,winapi,pretty_assertions,shared", "declared names in order: " + names);
        PackageEntry Get(string name, string group = "dependencies") => entries.Single(e => e.Name == name && e.Group == group);

        check(Get("serde").Requested == "1.0" && Get("serde").Source == null && Get("serde").Line == 7 && Get("serde").Scope == PackageScope.Runtime, "inline table with features");
        check(Get("anyhow").Requested == "1" && Get("anyhow").Line == 8, "plain string with a comment");
        check(entries.All(e => e.Name != "commented"), "commented entry ignored");
        check(Get("local").Source == "path" && Get("local").Requested == "0.2", "path dependency keeps its version");
        check(Get("fork").Source == "https://example.invalid/fork.git" && Get("fork").Requested == "", "git dependency: source is the url");
        check(Get("shared").Source == "workspace" && Get("shared").Requested == "" && Get("shared").Line == 12, "dotted workspace = true");
        check(Get("inherited").Source == "workspace" && Get("inherited").Line == 13, "inline workspace over several lines");
        check(Get("alias").Source == "package real-name" && Get("alias").Requested == "2.1" && Get("alias").Name == "alias", "renamed package: key is the name, real name in Source");
        check(Get("quoted-key").Requested == "0.3", "quoted key");
        check(Get("tokio").Requested == "1.30" && Get("tokio").Line == 19, "dotted keys of one dependency merge");
        check(Get("regex").Requested == "1.9" && Get("regex").Line == 22, "dependency table [dependencies.regex]");
        check(Get("criterion", "dev-dependencies").Scope == PackageScope.Development, "dev scope");
        check(Get("cc", "build-dependencies").Scope == PackageScope.Build, "build scope");
        check(Get("winapi", "target.cfg(windows).dependencies").Requested == "0.3" && Get("winapi", "target.cfg(windows).dependencies").Scope == PackageScope.Runtime, "target-specific runtime dependency");
        check(Get("pretty_assertions", "target.x86_64-unknown-linux-gnu.dev-dependencies").Scope == PackageScope.Development, "target-specific dev dependency");
        check(Get("shared", "workspace.dependencies").Requested == "3.1" && Get("shared", "workspace.dependencies").Scope == PackageScope.Runtime, "workspace.dependencies");
        check(entries.All(e => e.ManifestPath == manifest && e.Compatible == null && e.Latest == null), "no outdated data before a report");

        check(Get("serde").Current == "1.0.160" && Get("anyhow").Current == "1.0.70", "current from Cargo.lock");
        check(Get("alias").Current == "2.1.4", "current of a renamed dependency uses the real name");
        check(Get("fork").Current == null && Get("criterion", "dev-dependencies").Current == null, "not in the lock file: null");
    }

    private static void Locks(CargoPackageManager cargo, string root, Action<bool, string> check)
    {
        var workspace = Path.Combine(root, "cargo-ws");
        var member = Path.Combine(workspace, "crates", "member");
        Directory.CreateDirectory(member);
        File.WriteAllText(Path.Combine(workspace, "Cargo.toml"), "[workspace]\nmembers = [\"crates/*\"]\n");
        File.WriteAllText(Path.Combine(workspace, "Cargo.lock"), Lock);
        File.WriteAllText(Path.Combine(member, "Cargo.toml"), "[package]\nname = \"m\"\n[dependencies]\nrand = \"0.8\"\nrand2 = { package = \"rand\", version = \"0.7\" }\nvague = { package = \"rand\", version = \"*\" }\nanyhow = \"1\"\n");
        var entries = cargo.ReadManifest(Path.Combine(member, "Cargo.toml"));
        check(entries.Single(e => e.Name == "rand").Current == "0.8.5" && entries.Single(e => e.Name == "rand2").Current == "0.7.3", "several locked versions: the one the requirement allows");
        check(entries.Single(e => e.Name == "vague").Current == null, "ambiguous requirement leaves Current null");
        check(entries.Single(e => e.Name == "anyhow").Current == "1.0.70", "lock file of the parent workspace");

        var loose = Path.Combine(root, "cargo-loose", "inner");
        Directory.CreateDirectory(loose);
        File.WriteAllText(Path.Combine(root, "cargo-loose", "Cargo.lock"), Lock);
        File.WriteAllText(Path.Combine(root, "cargo-loose", "Cargo.toml"), "[package]\nname = \"outer\"\n");
        File.WriteAllText(Path.Combine(loose, "Cargo.toml"), "[package]\nname = \"inner\"\n[dependencies]\nanyhow = \"1\"\n");
        check(cargo.ReadManifest(Path.Combine(loose, "Cargo.toml")).Single().Current == null, "a parent lock file without [workspace] is not used");

        var missing = false;
        try { cargo.ReadManifest(Path.Combine(root, "nothing", "Cargo.toml")); } catch (PackageManagerException) { missing = true; }
        check(missing, "missing manifest raises PackageManagerException");
        var empty = Path.Combine(root, "cargo-empty.toml");
        File.WriteAllText(empty, "[package]\nname = \"a\"\n\n[dependencies]\n");
        check(cargo.ReadManifest(empty).Count == 0, "empty dependencies table");
    }

    private static void Report(CargoPackageManager cargo, string root, Action<bool, string> check)
    {
        // The manifest and lock of cargo's own report_behind test (dependencies and registry versions as published there).
        var folder = Path.Combine(root, "cargo-behind");
        Directory.CreateDirectory(folder);
        var manifest = Path.Combine(folder, "Cargo.toml");
        File.WriteAllText(manifest, "[package]\nname = \"foo\"\n\n[dependencies]\nbreaking = \"0.1\"\npre = \"=1.0.0-alpha.0\"\ntwo-ver = \"0.2.0\"\ntwo-ver-one = { version = \"0.1.0\", package = \"two-ver\" }\n");
        File.WriteAllText(Path.Combine(folder, "Cargo.lock"), "version = 3\n[[package]]\nname = \"breaking\"\nversion = \"0.1.0\"\n[[package]]\nname = \"foo\"\nversion = \"0.0.0\"\n[[package]]\nname = \"pre\"\nversion = \"1.0.0-alpha.0\"\n[[package]]\nname = \"two-ver\"\nversion = \"0.1.0\"\n[[package]]\nname = \"two-ver\"\nversion = \"0.2.0\"\n");
        var declared = cargo.ReadManifest(manifest);
        check(declared.Select(e => e.Current).SequenceEqual(new[] { "0.1.0", "1.0.0-alpha.0", "0.2.0", "0.1.0" }), "report_behind currents: " + string.Join(",", declared.Select(e => e.Current)));

        var command = cargo.CreateOutdated(Tool, manifest, declared);
        check(command.Count == 1 && command[0].Arguments == "update --dry-run --verbose" && command[0].WorkingDirectory == folder, "outdated command: " + command[0].Arguments);
        check(command[0].EnvironmentVariables["NO_COLOR"] == "1" && command[0].RedirectStandardError, "plain text, stderr captured");

        var merged = cargo.ApplyOutdated(declared, new[] { new PackageToolOutput(0, "", CargoSuiteOutput) });
        PackageEntry Pick(string name) => merged.Single(e => e.Name == name);
        var breaking = Pick("breaking");
        check(breaking.Current == "0.1.0" && breaking.Compatible == "0.1.1" && breaking.Latest == "0.2.0" && breaking.HasCompatibleUpdate, "Updating line: " + breaking.Caption);
        var pre = Pick("pre");
        check(pre.Current == "1.0.0-alpha.0" && pre.Compatible == "1.0.0-alpha.0" && pre.Latest == "1.0.0-alpha.1" && pre.IsOutdated && !pre.HasCompatibleUpdate, "pinned pre-release: newer exists outside the =requirement");
        var twoVer = Pick("two-ver");
        check(twoVer.Current == "0.2.0" && twoVer.Compatible == "0.2.0" && twoVer.Latest == "0.2.0" && !twoVer.IsOutdated, "second locked version of the same crate is current");
        var one = Pick("two-ver-one");
        check(one.Current == "0.1.0" && one.Compatible == "0.1.0" && one.Latest == "0.2.0", "renamed dependency matched by its real name: " + one.Caption);
        check(merged.Count == declared.Count, "same count");

        // stdout carries the same text, and a run with no status lines at all proves nothing.
        check(cargo.ApplyOutdated(declared, new[] { new PackageToolOutput(0, CargoSuiteOutput, "") }).Single(e => e.Name == "breaking").Latest == "0.2.0", "stdout is parsed too");
        var silent = cargo.ApplyOutdated(declared, new[] { new PackageToolOutput(0, "", "    Updating `x` index\n") });
        check(silent.All(e => e.Latest == null && e.Compatible == null), "no report lines: versions stay unknown");
        var locking = cargo.ApplyOutdated(declared, new[] { new PackageToolOutput(0, "", "     Locking 0 packages to highest compatible versions\n") });
        check(locking.All(e => e.Latest == e.Current), "a Locking line without Unchanged lines means everything is current");

        var more = cargo.ApplyOutdated(declared, new[] { new PackageToolOutput(0, "", "\u001b[1m\u001b[32m    Updating\u001b[0m breaking v0.1.0 -> v0.1.2\n   Downgrading two-ver v0.2.0 -> v0.1.9\n    Updating git repository `https://example.invalid/x`\n    Updating odd v1.0.0 (https://x#abcd1234) -> #deadbeef\n") });
        check(more.Single(e => e.Name == "breaking").Compatible == "0.1.2" && more.Single(e => e.Name == "breaking").Latest == "0.1.2", "colored Updating line without available, latest is the new version");
        check(more.Single(e => e.Name == "two-ver").Compatible == "0.1.9", "Downgrading line");

        var added = cargo.ApplyOutdated(new[] { new PackageEntry("fresh", "1", PackageScope.Runtime, "dependencies", manifest, 5) }, new[] { new PackageToolOutput(0, "", "      Adding fresh v1.4.0 (available: v2.0.0)\n    Locking 1 package\n") });
        check(added[0].Current == null && added[0].Compatible == "1.4.0" && added[0].Latest == "2.0.0", "Adding line for a package without a lock entry");

        var path = new PackageEntry("local", "0.2", PackageScope.Runtime, "dependencies", manifest, 3, "path", "0.2.0");
        check(cargo.ApplyOutdated(new[] { path }, new[] { new PackageToolOutput(0, "", CargoSuiteOutput) })[0].Latest == null, "path dependencies are never reported");

        var failed = false;
        try { cargo.ApplyOutdated(declared, new[] { new PackageToolOutput(101, "", "error: failed to get `x` as a dependency\n\nCaused by:\n  no network\n") }); }
        catch (PackageManagerException ex) { failed = ex.Message.Contains("failed to get") && ex.Message.Contains("no network"); }
        check(failed, "failed run raises PackageManagerException with cargo's message");
    }

    private static void Requirements(CargoPackageManager cargo, Action<bool, string> check)
    {
        // Each case: requirement, locked version, newer version cargo reports, whether it is reachable without a manifest change.
        var cases = new[]
        {
            Tuple.Create("1.2", "1.2.3", "1.9.0", true), Tuple.Create("1.2", "1.2.3", "2.0.0", false), Tuple.Create("^1.2.3", "1.2.3", "1.2.4", true),
            Tuple.Create("0.3", "0.3.1", "0.3.5", true), Tuple.Create("0.3", "0.3.1", "0.4.0", false), Tuple.Create("0.0.3", "0.0.3", "0.0.4", false),
            Tuple.Create("~1.2", "1.2.1", "1.2.9", true), Tuple.Create("~1.2", "1.2.1", "1.3.0", false), Tuple.Create("~1", "1.2.1", "1.9.0", true),
            Tuple.Create("=1.0.0", "1.0.0", "1.0.1", false), Tuple.Create(">=1, <2", "1.1.0", "1.5.0", true), Tuple.Create(">=1, <2", "1.1.0", "2.0.0", false),
            Tuple.Create("1.*", "1.1.0", "1.8.0", true), Tuple.Create("1.*", "1.1.0", "2.0.0", false), Tuple.Create("*", "1.1.0", "7.0.0", true),
            Tuple.Create(">1.2", "1.3.0", "1.4.0", true), Tuple.Create("<=1.2", "1.2.0", "1.3.0", false), Tuple.Create("", "1.1.0", "1.4.0", true),
            Tuple.Create("", "0.4.0", "0.5.0", false), Tuple.Create("1", "1.4.0", "2.0.0-rc.1", false), Tuple.Create("garbage!", "1.1.0", "1.4.0", true),
        };
        foreach (var c in cases)
        {
            var entry = new PackageEntry("x", c.Item1, PackageScope.Runtime, "dependencies", "Cargo.toml", 1, null, c.Item2);
            var report = "   Unchanged x v" + c.Item2 + " (available: v" + c.Item3 + ")\n";
            var result = cargo.ApplyOutdated(new[] { entry }, new[] { new PackageToolOutput(0, "", report) })[0];
            check(result.Latest == c.Item3 && (result.Compatible == c.Item3) == c.Item4, "requirement '" + c.Item1 + "' on " + c.Item2 + " with " + c.Item3 + " available: compatible=" + result.Compatible);
        }
    }

    private static void Commands(CargoPackageManager cargo, string manifest, string folder, Action<bool, string> check)
    {
        string Args(PackageAction action) => action.Commands.Single().Arguments;
        PackageEntry Entry(string name, PackageScope scope, string group, string? source = null, string? latest = "2.0.0", string requested = "1") =>
            new PackageEntry(name, requested, scope, group, manifest, 1, source, "1.0.0", "1.0.0", latest);

        var add = cargo.Add(Tool, manifest, new PackageRequest("serde", "1.0"));
        check(Args(add) == "add serde@1.0" && add.Description == "cargo add serde@1.0" && add.Edits.Count == 0 && add.Commands[0].WorkingDirectory == folder && add.Commands[0].FileName == Tool, "add: " + Args(add));
        check(Args(cargo.Add(Tool, manifest, new PackageRequest("serde"))) == "add serde", "add without version");
        check(Args(cargo.Add(Tool, manifest, new PackageRequest("criterion", "0.5", PackageScope.Development))) == "add criterion@0.5 --dev", "add dev");
        check(Args(cargo.Add(Tool, manifest, new PackageRequest("cc", null, PackageScope.Build))) == "add cc --build", "add build");
        check(Args(cargo.Add(Tool, manifest, new PackageRequest("serde", ">=1.0, <2"))) == "add \"serde@>=1.0, <2\"", "requirement with spaces is one argument");
        check(Args(cargo.Add(Tool, manifest, new PackageRequest("serde", null, PackageScope.Runtime, "my-registry"))) == "add serde --registry my-registry", "add from a named registry");
        Rejected(() => cargo.Add(Tool, manifest, new PackageRequest("serde", null, PackageScope.Runtime, "https://x.invalid/index")), "registry url", check);
        Rejected(() => cargo.Add(Tool, manifest, new PackageRequest("a/b")), "slash in a crate name", check);
        Rejected(() => cargo.Add(Tool, manifest, new PackageRequest("a@b")), "@ in a crate name", check);
        Rejected(() => cargo.Add("cargo.exe", manifest, new PackageRequest("serde")), "relative tool", check);

        check(Args(cargo.Remove(Tool, manifest, Entry("serde", PackageScope.Runtime, "dependencies"))) == "remove serde", "remove");
        check(Args(cargo.Remove(Tool, manifest, Entry("criterion", PackageScope.Development, "dev-dependencies"))) == "remove criterion --dev", "remove dev");
        check(Args(cargo.Remove(Tool, manifest, Entry("cc", PackageScope.Build, "build-dependencies"))) == "remove cc --build", "remove build");
        check(Args(cargo.Remove(Tool, manifest, Entry("winapi", PackageScope.Runtime, "target.cfg(windows).dependencies"))) == "remove winapi --target cfg(windows)", "remove target-specific");
        check(Args(cargo.Remove(Tool, manifest, Entry("pa", PackageScope.Development, "target.cfg(target_os = \"linux\").dev-dependencies"))) == "remove pa --dev --target \"cfg(target_os = \\\"linux\\\")\"", "remove target with quotes stays one argument");
        Rejected(() => cargo.Remove(Tool, manifest, Entry("shared", PackageScope.Runtime, "workspace.dependencies")), "remove from [workspace.dependencies]", check);

        check(Args(cargo.Update(Tool, manifest, null, false)) == "update", "update all");
        check(Args(cargo.Update(Tool, manifest, Entry("serde", PackageScope.Runtime, "dependencies"), false)) == "update serde", "update one");
        check(Args(cargo.Update(Tool, manifest, Entry("alias", PackageScope.Runtime, "dependencies", "package real-name"), false)) == "update real-name", "update a renamed one by its real name");
        var all = cargo.Update(Tool, manifest, null, true);
        check(Args(all) == "update" && all.Description.Contains("per package"), "update all to latest: lock file only, described: " + all.Description);
        check(Args(cargo.Update(Tool, manifest, Entry("serde", PackageScope.Runtime, "dependencies"), true)) == "add serde@2.0.0", "update to latest re-adds at the latest version");
        check(Args(cargo.Update(Tool, manifest, Entry("criterion", PackageScope.Development, "dev-dependencies", null, "0.6.0"), true)) == "add criterion@0.6.0 --dev", "update dev to latest");
        check(Args(cargo.Update(Tool, manifest, Entry("alias", PackageScope.Runtime, "dependencies", "package real-name"), true)) == "add real-name@2.0.0 --rename alias", "update renamed to latest");
        var noVersion = false;
        try { cargo.Update(Tool, manifest, Entry("serde", PackageScope.Runtime, "dependencies", null, null), true); }
        catch (PackageManagerException ex) { noVersion = ex.Message.Contains("check for updates"); }
        check(noVersion, "to latest without a known latest asks for a version check first");
        Rejected(() => cargo.Update(Tool, manifest, Entry("local", PackageScope.Runtime, "dependencies", "path"), true), "to latest for a path dependency", check);
        Rejected(() => cargo.Update(Tool, manifest, Entry("shared", PackageScope.Runtime, "dependencies", "workspace"), true), "to latest for an inherited dependency", check);

        var virtualManifest = Path.Combine(folder, "virtual", "Cargo.toml");
        Directory.CreateDirectory(Path.GetDirectoryName(virtualManifest)!);
        File.WriteAllText(virtualManifest, "[workspace]\nmembers = [\"a\"]\n[workspace.dependencies]\nx = \"1\"\n");
        Rejected(() => cargo.Add(Tool, virtualManifest, new PackageRequest("serde")), "add to a virtual manifest", check);
    }

    private static void Rejected(Action action, string what, Action<bool, string> check)
    {
        var rejected = false;
        try { action(); }
        catch (ArgumentException) { rejected = true; }
        catch (PackageManagerException) { rejected = true; }
        check(rejected, "rejected: " + what);
    }

    /// <summary>A throwaway crate with an old pinned dependency; runs only when cargo is installed.</summary>
    internal static async Task<bool> RunLiveAsync(string root, Action<bool, string> check)
    {
        var tool = FindCargo();
        if (tool == null) { Console.WriteLine("SKIP: cargo not found on PATH or in %USERPROFILE%\\.cargo\\bin; live Cargo checks skipped."); return false; }
        var cargo = new CargoPackageManager();
        var folder = Path.Combine(root, "cargo-live");
        Directory.CreateDirectory(Path.Combine(folder, "src"));
        var manifest = Path.Combine(folder, "Cargo.toml");
        File.WriteAllText(Path.Combine(folder, "src", "lib.rs"), "");
        // fnv 1.0.6 is old; "1.0.6" allows 1.0.x, and a newer 1.0.x exists.
        File.WriteAllText(manifest, "[package]\nname = \"cargo_live\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dependencies]\nfnv = \"1.0.6\"\n");

        var started = Stopwatch.StartNew();
        // Pin the old version in the lock file first so that the dry run has something to update.
        check((await RunAsync(Start(tool, folder, "generate-lockfile"))).ExitCode == 0, "live: generate-lockfile");
        check((await RunAsync(Start(tool, folder, "update", "fnv", "--precise", "1.0.6"))).ExitCode == 0, "live: lock fnv at 1.0.6");
        var before = cargo.ReadManifest(manifest);
        check(before.Single().Current == "1.0.6", "live: current 1.0.6 from Cargo.lock: " + before.Single().Current);

        var report = new List<PackageToolOutput>();
        foreach (var command in cargo.CreateOutdated(tool, manifest, before)) report.Add(await RunAsync(command));
        Console.WriteLine("cargo live: " + report[0].StandardError.Trim());
        var after = cargo.ApplyOutdated(before, report).Single();
        check(after.HasCompatibleUpdate, "live: fnv 1.0.6 has a compatible update: " + after.Caption);

        await RunActionAsync(cargo.Add(tool, manifest, new PackageRequest("itoa", "1")), check, "add itoa");
        await RunActionAsync(cargo.Add(tool, manifest, new PackageRequest("semver", null, PackageScope.Development)), check, "add dev semver");
        var added = cargo.ReadManifest(manifest);
        check(added.Any(e => e.Name == "itoa" && e.Scope == PackageScope.Runtime) && added.Any(e => e.Name == "semver" && e.Scope == PackageScope.Development), "live: added entries re-read");
        await RunActionAsync(cargo.Update(tool, manifest, added.Single(e => e.Name == "fnv"), false), check, "update fnv");
        check(cargo.ReadManifest(manifest).Single(e => e.Name == "fnv").Current != "1.0.6", "live: update moved the locked version");
        await RunActionAsync(cargo.Remove(tool, manifest, added.Single(e => e.Name == "itoa")), check, "remove itoa");
        check(cargo.ReadManifest(manifest).All(e => e.Name != "itoa"), "live: itoa removed");
        check(started.Elapsed < TimeSpan.FromMinutes(2), "live: cargo run took " + started.Elapsed.TotalSeconds.ToString("0") + "s");
        return true;
    }

    private static string? FindCargo()
    {
        var folders = (Environment.GetEnvironmentVariable("PATH") ?? "").Split(Path.PathSeparator).ToList();
        folders.Add(Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".cargo", "bin"));
        foreach (var folder in folders)
        {
            try
            {
                var exe = Path.Combine(folder.Trim().Trim('"'), "cargo.exe");
                if (Path.IsPathRooted(exe) && File.Exists(exe)) return exe;
            }
            catch (ArgumentException) { }
        }
        return null;
    }

    private static ProcessStartInfo Start(string tool, string folder, params string[] arguments) =>
        Vistudio.Core.ProcessCommands.CreateRedirected(tool, PackageArguments.Join(arguments), folder);

    private static async Task RunActionAsync(PackageAction action, Action<bool, string> check, string what)
    {
        foreach (var command in action.Commands)
        {
            var output = await RunAsync(command);
            check(output.ExitCode == 0, "live: " + what + " (" + action.Description + ") exit " + output.ExitCode + ": " + output.StandardError.Trim());
        }
    }

    private static async Task<PackageToolOutput> RunAsync(ProcessStartInfo start)
    {
        using (var process = Process.Start(start)!)
        {
            process.StandardInput.Close();
            var output = process.StandardOutput.ReadToEndAsync();
            var error = process.StandardError.ReadToEndAsync();
            if (!process.WaitForExit(100000)) { try { process.Kill(); } catch (InvalidOperationException) { } return new PackageToolOutput(-1, "", "timed out: " + start.Arguments); }
            return new PackageToolOutput(process.ExitCode, await output, await error);
        }
    }
