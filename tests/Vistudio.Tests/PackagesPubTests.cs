    // Shape taken from a real `dart pub outdated --json --show-all` run (Dart 3.14.0), trimmed to two packages.
    private const string OutdatedJson = @"{
  ""packages"": [
    { ""package"": ""http"", ""kind"": ""direct"", ""isDiscontinued"": false, ""replacedBy"": null, ""isCurrentRetracted"": false,
      ""current"": { ""version"": ""1.2.1"" }, ""upgradable"": { ""version"": ""1.2.2"" }, ""resolvable"": { ""version"": ""1.2.2"" }, ""latest"": { ""version"": ""2.0.0"" } },
    { ""package"": ""lints"", ""kind"": ""dev"", ""current"": { ""version"": ""3.0.0"" }, ""upgradable"": { ""version"": ""3.0.0"" }, ""resolvable"": { ""version"": ""3.0.0"" }, ""latest"": { ""version"": ""3.0.0"" } },
    { ""package"": ""web"", ""kind"": ""transitive"", ""current"": { ""version"": ""0.5.0"" }, ""upgradable"": { ""version"": ""0.5.0"" }, ""resolvable"": null, ""latest"": null }
  ]
}";

    internal static void Run(string root, Action<bool, string> check)
    {
        var folder = Path.Combine(root, "pub-unit");
        Directory.CreateDirectory(folder);
        var manifest = Path.Combine(folder, "pubspec.yaml");
        File.WriteAllText(manifest, Pubspec);
        File.WriteAllText(Path.Combine(folder, "pubspec.lock"), Lock);
        var pub = new PubPackageManager();

        check(pub.Ecosystem == PackageEcosystem.Pub && pub.DisplayName == "pub" && pub.ManifestNames.SequenceEqual(new[] { "pubspec.yaml" }), "pub identity");

        var entries = pub.ReadManifest(manifest);
        var names = string.Join(",", entries.Select(e => e.Name));
        check(names == "flutter,http,collection,meta,quoted,local_pkg,from_git,mirror,hosted_map,inline,flutter_test,lints", "declared names in order: " + names);
        PackageEntry Get(string name) => entries.Single(e => e.Name == name);

        check(Get("http").Requested == "^1.2.0" && Get("http").Scope == PackageScope.Runtime && Get("http").Group == "dependencies" && Get("http").Source == null, "caret constraint");
        check(Get("http").Line == 8 && Get("collection").Line == 10 && Get("lints").Line == 31, "1-based lines: " + Get("http").Line + "/" + Get("collection").Line + "/" + Get("lints").Line);
        check(Get("collection").Requested == "" && Get("meta").Requested == "any", "empty and any constraints");
        check(Get("quoted").Requested == "^2.0.0", "quoted constraint with a trailing comment");
        check(Get("flutter").Source == "sdk" && Get("flutter").Requested == "" && Get("flutter_test").Source == "sdk", "sdk dependencies");
        check(Get("local_pkg").Source == "path" && Get("inline").Source == "path", "path dependencies, block and flow");
        check(Get("from_git").Source == "git", "git dependency");
        check(Get("mirror").Source == "https://pub.example.invalid" && Get("mirror").Requested == ">=1.0.0 <2.0.0", "hosted scalar with version");
        check(Get("hosted_map").Source == "https://pub.example.invalid/api" && Get("hosted_map").Requested == "^3.1.0", "hosted map with url and version");
        check(Get("lints").Scope == PackageScope.Development && Get("lints").Group == "dev_dependencies", "dev dependency scope");
        check(entries.All(e => e.Name != "uses-material-design") && entries.Count(e => e.Name == "http") == 1, "overrides and other sections ignored");
        check(Get("http").Current == "1.2.1" && Get("lints").Current == "3.0.0" && Get("flutter").Current == "0.0.0" && Get("meta").Current == null, "current versions from pubspec.lock only");
        check(entries.All(e => e.Compatible == null && e.Latest == null && e.ManifestPath == manifest), "no outdated data before a report");

        var noLock = Path.Combine(folder, "nolock");
        Directory.CreateDirectory(noLock);
        File.WriteAllText(Path.Combine(noLock, "pubspec.yaml"), "name: a\ndependencies:\n  x: ^1.0.0\n");
        check(pub.ReadManifest(Path.Combine(noLock, "pubspec.yaml")).Single().Current == null, "no lock file, no current");
        File.WriteAllText(Path.Combine(noLock, "pubspec.yaml"), "name: a\r\ndependencies:\r\n  x: ^1.0.0\r\n  y: 2.0.0\r\n");
        var crlf = pub.ReadManifest(Path.Combine(noLock, "pubspec.yaml"));
        check(crlf.Count == 2 && crlf[1].Requested == "2.0.0" && crlf[1].Line == 4, "CRLF manifest");
        File.WriteAllText(Path.Combine(noLock, "pubspec.yaml"), "name: a\n");
        check(pub.ReadManifest(Path.Combine(noLock, "pubspec.yaml")).Count == 0, "manifest without dependencies");
        var missing = false;
        try { pub.ReadManifest(Path.Combine(noLock, "missing.yaml")); } catch (PackageManagerException) { missing = true; }
        check(missing, "missing manifest raises PackageManagerException");

        var tool = @"C:\sdk\bin\dart.exe";
        var outdated = pub.CreateOutdated(tool, manifest, entries);
        check(outdated.Count == 1 && outdated[0].FileName == tool && outdated[0].Arguments == "pub outdated --json --show-all" && outdated[0].WorkingDirectory == folder, "outdated command: " + outdated[0].Arguments);
        check(outdated[0].EnvironmentVariables["PUB_ENVIRONMENT"] == "vistudio" && outdated[0].RedirectStandardOutput && !outdated[0].UseShellExecute, "environment comes from DartCommandFactory");

        var merged = pub.ApplyOutdated(entries, new[] { new PackageToolOutput(0, "Resolving...\n" + OutdatedJson, "") });
        check(merged.Count == entries.Count && merged.Select(e => e.Name).SequenceEqual(entries.Select(e => e.Name)), "same order and count");
        var http = merged.Single(e => e.Name == "http");
        check(http.Current == "1.2.1" && http.Compatible == "1.2.2" && http.Latest == "2.0.0" && http.IsOutdated && http.HasCompatibleUpdate, "http: compatible and latest");
        check(http.Caption == "http 1.2.1 \u2192 2.0.0", "caption: " + http.Caption);
        var lints = merged.Single(e => e.Name == "lints");
        check(lints.Latest == "3.0.0" && !lints.IsOutdated, "lints is up to date");
        var untouched = merged.Single(e => e.Name == "local_pkg");
        check(untouched.Current == null && untouched.Latest == null, "packages absent from the report are left alone");
        check(!merged.Any(e => e.Name == "web"), "transitive packages are not added");
        var failed = false;
        try { pub.ApplyOutdated(entries, new[] { new PackageToolOutput(1, "", "pub failed: no network") }); }
        catch (PackageManagerException ex) { failed = ex.Message.Contains("no network"); }
        check(failed, "failed report raises PackageManagerException with the message");
        var broken = false;
        try { pub.ApplyOutdated(entries, new[] { new PackageToolOutput(0, "not json", "") }); } catch (PackageManagerException) { broken = true; }
        check(broken, "non-JSON output raises PackageManagerException");

        var add = pub.Add(tool, manifest, new PackageRequest("http", "^1.2.0"));
        check(add.Commands.Count == 1 && add.Commands[0].Arguments == "pub add http@^1.2.0" && add.Description == "dart pub add http@^1.2.0" && add.Edits.Count == 0, "add runtime: " + add.Commands[0].Arguments);
        check(pub.Add(tool, manifest, new PackageRequest("lints", null, PackageScope.Development)).Commands[0].Arguments == "pub add dev:lints", "add dev without constraint");
        check(pub.Add(tool, manifest, new PackageRequest("meta", ">=1.0.0 <2.0.0")).Commands[0].Arguments == "pub add \"meta@>=1.0.0 <2.0.0\"", "constraint with spaces is one argument");
        check(pub.Add(tool, manifest, new PackageRequest("x", null, PackageScope.Runtime, "https://pub.example.invalid")).Commands[0].Arguments == "pub add x --hosted-url https://pub.example.invalid", "hosted url");
        Rejected(() => pub.Add(tool, manifest, new PackageRequest("x", null, PackageScope.Build)), "build scope", check);
        Rejected(() => pub.Add(tool, manifest, new PackageRequest("a:b")), "name with a colon", check);
        Rejected(() => pub.Add(tool, manifest, new PackageRequest("a@b")), "name with @", check);
        Rejected(() => pub.Add(tool, manifest, new PackageRequest("a/b")), "name with a slash", check);
        Rejected(() => pub.Add("dart.exe", manifest, new PackageRequest("a")), "relative tool path", check);
        check(pub.Remove(tool, manifest, Get("http")).Commands[0].Arguments == "pub remove http", "remove");
        check(pub.Update(tool, manifest, null, false).Commands[0].Arguments == "pub upgrade", "update all");
        check(pub.Update(tool, manifest, Get("http"), false).Commands[0].Arguments == "pub upgrade http", "update one");
        check(pub.Update(tool, manifest, null, true).Commands[0].Arguments == "pub upgrade --major-versions", "update all to latest");
        check(pub.Update(tool, manifest, Get("http"), true).Commands[0].Arguments == "pub upgrade --major-versions http", "update one to latest");
        check(add.Commands[0].WorkingDirectory == folder, "working directory is the manifest folder");
    }

    private static void Rejected(Action action, string what, Action<bool, string> check)
    {
        var rejected = false;
        try { action(); }
        catch (ArgumentException) { rejected = true; }
        catch (PackageManagerException) { rejected = true; }
        check(rejected, "rejected: " + what);
    }

    /// <summary>A throwaway package with an old pinned dependency against the real pub.dev, through the real dart.exe.</summary>
    internal static async Task<bool> RunLiveAsync(string root, Action<bool, string> check)
    {
        var sdk = FindSdk();
        if (sdk == null) { Console.WriteLine("SKIP: dart.exe not found; live pub checks skipped."); return false; }
        var pub = new PubPackageManager();
        var folder = Path.Combine(root, "pub-live");
        Directory.CreateDirectory(folder);
        var manifest = Path.Combine(folder, "pubspec.yaml");
        // path 1.8.0 is pinned on purpose: newer releases exist and the pin keeps them outside the constraint.
        File.WriteAllText(manifest, "name: pub_live\ndescription: throwaway\nenvironment:\n  sdk: '>=3.0.0 <4.0.0'\ndependencies:\n  path: 1.8.0\n  collection: ^1.17.0\n");

        var started = Stopwatch.StartNew();
        Console.WriteLine("pub live: " + sdk.Dart);
        var get = await RunAsync(DartCommandFactory.PubGet(sdk, DartProject.FromPubspec(folder, File.ReadAllText(manifest))));
        check(get.ExitCode == 0, "live: dart pub get: " + get.StandardError.Trim() + get.StandardOutput.Trim());

        var before = pub.ReadManifest(manifest);
        check(before.Count == 2 && before.Single(e => e.Name == "path").Current == "1.8.0", "live: lock file gives current path 1.8.0");

        var report = await RunAllAsync(pub.CreateOutdated(sdk.Dart, manifest, before));
        var after = pub.ApplyOutdated(before, report);
        var path = after.Single(e => e.Name == "path");
        check(path.IsOutdated && path.Latest != null && PackageVersion.Compare(path.Latest!, "1.8.0") > 0, "live: path 1.8.0 is outdated, latest " + path.Latest);
        check(path.Compatible == "1.8.0", "live: the pin keeps the compatible version at 1.8.0: " + path.Compatible);
        var collection = after.Single(e => e.Name == "collection");
        check(collection.Current != null && collection.Latest != null && !collection.HasCompatibleUpdate, "live: collection is resolved, nothing compatible left: " + collection.Caption);
        Console.WriteLine("pub live: outdated -> " + string.Join("; ", after.Select(e => e.Caption)));

        await RunActionAsync(pub.Add(sdk.Dart, manifest, new PackageRequest("meta", "^1.9.0")), check, "add meta");
        await RunActionAsync(pub.Add(sdk.Dart, manifest, new PackageRequest("lints", null, PackageScope.Development)), check, "add dev lints");
        var added = pub.ReadManifest(manifest);
        var meta = added.SingleOrDefault(e => e.Name == "meta");
        var lints = added.SingleOrDefault(e => e.Name == "lints");
        check(meta != null && meta.Scope == PackageScope.Runtime && meta.Requested.StartsWith("^1.", StringComparison.Ordinal) && meta.Current != null, "live: meta added with a constraint and a locked version: " + meta?.Requested + "/" + meta?.Current);
        check(lints != null && lints.Scope == PackageScope.Development && lints.Requested.StartsWith("^", StringComparison.Ordinal), "live: lints added to dev_dependencies: " + lints?.Requested);

        await RunActionAsync(pub.Update(sdk.Dart, manifest, null, false), check, "update within constraints");
        check(pub.ReadManifest(manifest).Single(e => e.Name == "path").Requested == "1.8.0", "live: update inside constraints leaves the pin");

        await RunActionAsync(pub.Update(sdk.Dart, manifest, pub.ReadManifest(manifest).Single(e => e.Name == "path"), true), check, "upgrade path to latest");
        var upgraded = pub.ReadManifest(manifest).Single(e => e.Name == "path");
        check(upgraded.Current != null && PackageVersion.Compare(upgraded.Current!, "1.8.0") > 0 && upgraded.Requested != "1.8.0", "live: --major-versions moved path and rewrote the constraint: " + upgraded.Requested + "/" + upgraded.Current);

        await RunActionAsync(pub.Remove(sdk.Dart, manifest, pub.ReadManifest(manifest).Single(e => e.Name == "meta")), check, "remove meta");
        check(pub.ReadManifest(manifest).All(e => e.Name != "meta"), "live: meta removed from the manifest");
        check(started.Elapsed < TimeSpan.FromMinutes(2), "live: pub run took " + started.Elapsed.TotalSeconds.ToString("0") + "s");
        return true;
    }

    private static async Task RunActionAsync(PackageAction action, Action<bool, string> check, string what)
    {
        foreach (var command in action.Commands)
        {
            var output = await RunAsync(command);
            check(output.ExitCode == 0, "live: " + what + " (" + action.Description + ") exit " + output.ExitCode + ": " + output.StandardError.Trim() + output.StandardOutput.Trim());
        }
    }

    private static async Task<IReadOnlyList<PackageToolOutput>> RunAllAsync(IEnumerable<ProcessStartInfo> commands)
    {
        var outputs = new List<PackageToolOutput>();
        foreach (var command in commands) outputs.Add(await RunAsync(command));
        return outputs;
    }

    private static async Task<PackageToolOutput> RunAsync(ProcessStartInfo start)
    {
        using (var process = Process.Start(start)!)
        {
            process.StandardInput.Close();
            var output = process.StandardOutput.ReadToEndAsync();
            var error = process.StandardError.ReadToEndAsync();
            if (!process.WaitForExit(100000)) { try { process.Kill(); } catch (InvalidOperationException) { } return new PackageToolOutput(-1, "", "timed out: " + start.Arguments); }
            return new PackageToolOutput(process.ExitCode, await output, await error);
        }
    }

    private static DartSdk? FindSdk()
    {
        var found = DartToolchain.Find(new DartSettings());
        if (found != null) return found;
        var flutter = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), "tools", "flutter");
        return Directory.Exists(flutter) ? DartToolchain.Find(new DartSettings { FlutterSdkPath = flutter }) : null;
    }
